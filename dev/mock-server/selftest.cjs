'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { setTimeout: delay } = require('node:timers/promises');
const { createMockServer } = require('./server.cjs');

test('real HTTP onboarding, CSRF, authorization, groups, import and session isolation', async t => {
  const server = createMockServer({ scannedMs: 80, authorizedMs: 300, expiresMs: 5000, outcome: 'authorized' });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const origin = `http://127.0.0.1:${server.address().port}`;
  function client() {
    const jar = new Map();
    return async (path, { method = 'GET', body, csrf = true, requestOrigin = origin, expected = 200 } = {}) => {
      const headers = { Cookie: [...jar].map(([k, v]) => `${k}=${v}`).join('; ') };
      if (method !== 'GET') headers.Origin = requestOrigin;
      if (csrf && jar.has('academic_csrf')) headers['X-CSRF-Token'] = jar.get('academic_csrf');
      if (body !== undefined) headers['Content-Type'] = 'application/json';
      const response = await fetch(`${origin}/api/v1${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
      for (const cookie of response.headers.getSetCookie()) {
        const [k, v] = cookie.split(';')[0].split('=');
        if (v) jar.set(k, v); else jar.delete(k);
      }
      const data = response.status === 204 ? null : await response.json();
      assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(data)}`);
      if (expected >= 400) { assert.ok(data.error.code); assert.ok(data.error.message); assert.ok(data.request_id); }
      return { data, headers: response.headers };
    };
  }
  const a = client(), b = client();
  const pre = await a('/auth/me', { expected: 401 });
  assert.match(pre.headers.get('set-cookie'), /academic_mock_session=.*HttpOnly/);
  assert.match(pre.headers.get('set-cookie'), /academic_csrf=/);
  const credentials = { username: 'student', password: 'correct-password' };
  await a('/auth/login', { method: 'POST', body: credentials, csrf: false, expected: 403 });
  await a('/auth/login', { method: 'POST', body: credentials, requestOrigin: 'https://evil.invalid', expected: 403 });
  await a('/auth/login', { method: 'POST', body: { ...credentials, password: 'wrong' }, expected: 401 });
  const { data: user } = await a('/auth/login', { method: 'POST', body: credentials });
  assert.equal(user.id, 'mock-student');
  assert.equal((await a('/auth/me')).data.username, 'student');
  assert.equal((await a('/platforms/sources')).data.items.length, 4);
  await b('/auth/me', { expected: 401 });
  await b('/auth/login', { method: 'POST', body: credentials });
  assert.deepEqual((await b('/platforms/connections')).data.items, []);
  const { data: link } = await a('/dws/link', { method: 'POST', expected: 202 });
  assert.equal(link.status, 'pending');
  assert.match(link.verification_uri, /^https:\/\/mock-auth\.invalid\//);
  assert.match(link.user_code, /^MOCK-/);
  const pollPath = `/dws/connections/${link.connection_id}/link/${link.id}`;
  await delay(110);
  assert.equal((await a(pollPath)).data.status, 'scanned');
  await delay(220);
  assert.equal((await a(pollPath)).data.status, 'authorized');
  const groupPath = `/dws/connections/${link.connection_id}`;
  const first = (await a(`${groupPath}/available-groups`)).data;
  assert.equal(first.has_more, true);
  const second = (await a(`${groupPath}/available-groups?cursor=${first.next_cursor}`)).data;
  assert.equal(second.has_more, false);
  await a(`${groupPath}/available-groups?cursor=bogus`, { expected: 400 });
  const groups = [first.items[0], second.items[0]];
  await a(`${groupPath}/groups`, { method: 'PUT', body: { groups }, expected: 204 });
  assert.deepEqual((await a(`${groupPath}/groups`)).data.items, groups);
  await a(`${groupPath}/groups`, { method: 'PUT', body: { groups: [groups[0], groups[0]] }, expected: 400 });
  await b(`${groupPath}/groups`, { expected: 404 });
  await a(pollPath, { method: 'DELETE' });
  assert.equal((await a(pollPath)).data.status, 'authorized', 'cancelling authorized challenge must not disconnect');
  const { data: cx } = await a('/platforms/chaoxing/auth', { method: 'POST', expected: 201 });
  await delay(330);
  assert.equal((await a(`/platforms/connections/${cx.connection.id}/auth`)).data.status, 'authorized');
  await a('/platforms/jwxt/login', { method: 'POST', body: { username: 'real-user', password: 'not-accepted' }, expected: 400 });
  const { data: school } = await a('/platforms/jwxt/login', { method: 'POST', body: { username: 'synthetic-student', password: 'synthetic-school-password' }, expected: 201 });
  const syncPath = `/platforms/connections/${school.id}/sync`;
  const schedule = { resource: 'schedule', academic_year: 2026, term: 1, calendar: { week_one_monday: '2026-09-07', periods: [{ period: 1, start: '08:00', end: '08:45' }, { period: 2, start: '08:55', end: '09:40' }] } };
  const { data: imported } = await a(syncPath, { method: 'POST', body: schedule });
  assert.equal(imported.records, 3); assert.equal(imported.generated, 48);
  await a(syncPath, { method: 'POST', body: { ...schedule, calendar: { ...schedule.calendar, week_one_monday: '2026-09-08' } }, expected: 400 });
  await a(syncPath, { method: 'POST', body: { ...schedule, calendar: { ...schedule.calendar, periods: [{ period: 1, start: '08:00', end: '08:45' }, { period: 2, start: '08:30', end: '09:40' }] } }, expected: 400 });
  await a(syncPath, { method: 'POST', body: schedule });
  const status = (await a('/mock/status')).data;
  assert.equal(status.imports.length, 1, 'reimport replaces same term');
  assert.ok(!JSON.stringify(status).includes('synthetic-school-password'));
  assert.deepEqual((await b('/dws/connections')).data.items, []);
  await a('/mock/config', { method: 'POST', body: { scannedMs: -1 }, expected: 400 });
  await a('/mock/config', { method: 'POST', body: { outcome: 'unknown' }, expected: 400 });
  await a('/mock/config', { method: 'POST', body: { scannedMs: 0, authorizedMs: 20, expiresMs: 1000, outcome: 'failed' } });
  const failed = (await a('/platforms/mooc/auth', { method: 'POST', expected: 201 })).data;
  await delay(30);
  assert.equal((await a(`/platforms/connections/${failed.connection.id}/auth`)).data.status, 'failed');
  await a('/mock/config', { method: 'POST', body: { scannedMs: 0, authorizedMs: 10, expiresMs: 25, outcome: 'expired' } });
  const expired = (await a('/dws/link', { method: 'POST', expected: 202 })).data;
  await delay(35);
  assert.equal((await a(`/dws/connections/${expired.connection_id}/link/${expired.id}`)).data.status, 'expired');
  await a('/mock/config', { method: 'POST', body: { scannedMs: 2000, authorizedMs: 4500, expiresMs: 120000, outcome: 'authorized' } });
  const cancelled = (await a('/dws/link', { method: 'POST', expected: 202 })).data;
  assert.equal((await a(`/dws/connections/${cancelled.connection_id}/link/${cancelled.id}`, { method: 'DELETE' })).data.status, 'cancelled');
  const uc = (await a('/platforms/ucampus/auth', { method: 'POST', expected: 201 })).data;
  await a(`/platforms/connections/${uc.connection.id}/`, { method: 'DELETE', expected: 204 });
  await a(`/platforms/connections/${uc.connection.id}/auth`, { expected: 404 });
  await a('/mock/reset', { method: 'POST' });
  assert.deepEqual((await a('/platforms/connections')).data.items, []);
  assert.equal((await a('/mock/status')).data.imports.length, 0);
  await a('/auth/logout', { method: 'POST', expected: 204 });
  await a('/auth/me', { expected: 401 });
  assert.equal((await b('/auth/me')).data.username, 'student', 'logout isolated from other client');
});
