import { test, expect } from '@playwright/test'

test('群选择说明、搜索初始焦点和90到100额度提示', async ({ page }) => {
  const groups = Array.from({ length: 102 }, (_, i) => ({ id: `group-${i}`, name: `课程群${i}` }))
  await page.route('**/api/v1/**', async (route) => {
    const path = new URL(route.request().url()).pathname.replace('/api/v1', '')
    const json = (data: unknown) => route.fulfill({ contentType: 'application/json', body: JSON.stringify(data) })
    if (path === '/auth/me') return json({ id: 'group-limit-student', username: 'student', role: 'user' })
    if (path === '/platforms/sources') return json({ items: [] })
    if (path === '/platforms/connections') return json({ items: [] })
    if (path === '/dws/connections') return json({ items: [{ id: 'dws-limit', user_id: 'group-limit-student', state: 'active', enabled: true }] })
    if (path.endsWith('/available-groups')) return json({ items: groups, has_more: false })
    if (path.endsWith('/groups')) return json({ items: groups.slice(0, 89) })
    return json({ items: [] })
  })
  await page.goto('/')
  const trigger = page.getByRole('button', { name: '选择群', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveAccessibleDescription(/只读取你勾选的群/)
  await expect(page.getByRole('textbox', { name: '搜索已加载的群' })).toBeFocused()
  await expect(page.getByLabel('课程群89', { exact: true })).toBeEnabled()
  await page.getByLabel('课程群89', { exact: true }).check()
  await expect(dialog.getByRole('status')).toHaveText('还可选择 10 个群。')
  for (let i = 90; i < 100; i++) await page.getByLabel(`课程群${i}`, { exact: true }).check()
  const extra = page.getByLabel('课程群100', { exact: true })
  await expect(dialog.getByRole('status')).toHaveText('最多选择 100 个，请先取消一个。')
  await expect(extra).toBeDisabled()
  await expect(extra).toHaveAccessibleDescription('最多选择 100 个，请先取消一个。')
  await page.getByLabel('课程群99', { exact: true }).uncheck()
  await expect(extra).toBeEnabled()
  await expect(dialog.getByRole('status')).toHaveText('还可选择 1 个群。')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('课程详情关联说明并聚焦主操作，关闭后恢复触发按钮', async ({ page }) => {
  await page.goto('/?demo=1')
  const trigger = page.getByRole('button', { name: '查看高等数学详情', exact: true })
  await trigger.click()
  await expect(page.getByRole('dialog')).toHaveAttribute('aria-describedby', /.+/)
  await expect(page.getByRole('dialog')).toHaveAccessibleDescription(/.+/)
  await expect(page.getByRole('button', { name: '和助手一起安排' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('清空新对话先确认，取消保留消息，确认取消旧回复并聚焦输入', async ({ page }) => {
  await page.clock.install()
  await page.goto('/?demo=1')
  await page.getByRole('button', { name: '打开学习助手' }).click()
  await page.clock.fastForward(800)
  const input = page.getByRole('textbox', { name: '向学习助手提问' })
  await input.fill('帮我检查任务')
  await page.getByRole('button', { name: '发送消息' }).click()
  const clear = page.getByRole('button', { name: '清空并新建', exact: true })
  await clear.click()
  await expect(page.getByRole('button', { name: '保留对话' })).toBeFocused()
  await expect(page.getByRole('dialog')).toHaveAccessibleDescription(/当前消息将被清空/)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('region', { name: 'Academic Assistant 对话区域' })).toBeVisible()
  await expect(page.getByRole('log')).toContainText('帮我检查任务')
  await expect(clear).toBeFocused()
  await clear.click()
  await page.getByRole('button', { name: '确认清空并新建', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(input).toBeFocused()
  await page.clock.fastForward(10_000)
  await expect(page.getByRole('log')).toHaveCount(0)
  await expect(input).toHaveValue('')
})
